import { createHmac, timingSafeEqual } from "node:crypto";

/**
 * What a session cookie asserts.
 *
 * `sessionId` names one row in `AuthSession` — one device (phase 10). It is what
 * makes "end that device" possible: the account-wide `sessionVersion` can only
 * end every session at once, because every cookie carries the same number, while
 * the row is per-device and is resolved on every request. A cookie that names no
 * row is therefore not a session at all, which is why the claim is required here
 * rather than optional.
 */
export type SessionClaims = {
  userId: string;
  walletIdentityId: string;
  sessionId: string;
  chainNamespace: "eip155";
  chainReference: string;
  sessionVersion: number;
  issuedAt: number;
  expiresAt: number;
};

/** Session ids are 16 random bytes in hex, generated by `createSessionId`. */
const SESSION_ID_PATTERN = /^[a-f0-9]{32}$/;

export function createSessionCookieValue(claims: SessionClaims, secret: string): string {
  const payload = Buffer.from(JSON.stringify(claims)).toString("base64url");
  const signature = createHmac("sha256", secret).update(payload).digest("base64url");
  return `${payload}.${signature}`;
}

export function verifySessionCookieValue(value: string, secret: string, nowSeconds = Math.floor(Date.now() / 1000)): SessionClaims | null {
  if (value.length > 1024) return null;
  const [payload, signature, extra] = value.split(".");
  if (!payload || !signature || extra || !/^[A-Za-z0-9_-]+$/.test(payload)) return null;

  const expected = createHmac("sha256", secret).update(payload).digest();
  let received: Buffer;
  try {
    received = Buffer.from(signature, "base64url");
  } catch {
    return null;
  }
  if (received.length !== expected.length || !timingSafeEqual(received, expected)) return null;

  let claims: SessionClaims;
  try {
    claims = JSON.parse(Buffer.from(payload, "base64url").toString("utf8")) as SessionClaims;
  } catch {
    return null;
  }

  if (
    !claims ||
    typeof claims.userId !== "string" ||
    typeof claims.walletIdentityId !== "string" ||
    typeof claims.sessionId !== "string" ||
    !SESSION_ID_PATTERN.test(claims.sessionId) ||
    claims.chainNamespace !== "eip155" ||
    typeof claims.chainReference !== "string" ||
    !Number.isSafeInteger(claims.sessionVersion) ||
    claims.sessionVersion < 0 ||
    !Number.isSafeInteger(claims.issuedAt) ||
    !Number.isSafeInteger(claims.expiresAt) ||
    claims.issuedAt > nowSeconds + 30 ||
    claims.expiresAt <= nowSeconds ||
    claims.expiresAt <= claims.issuedAt ||
    claims.expiresAt - claims.issuedAt > 8 * 60 * 60 + 30
  ) {
    return null;
  }

  return claims;
}

/** The parts of a `User` row a session cookie is only as good as. */
export type SessionSubject = { status: string; sessionVersion: number } | null;

/**
 * Whether an authentic, unexpired cookie still describes this account.
 *
 * The *account-wide* half of the two rules a request is held to. It is shared by
 * the two places that need it: `session-store.ts`, which resolves the current
 * user on every page and route, and the sign-out route, which decides whether
 * this cookie is still the live one before rotating it. Signing out increments
 * `sessionVersion`, so the already-issued cookie stops matching the user it names
 * — which is why a captured cookie cannot be replayed after a sign-out, and why
 * the check has to be the same in both places.
 *
 * The other half arrived with the `sessionId` claim and lives in
 * `session-record.ts` (`sessionIsUsable`): the row this cookie names must still
 * be live. One epoch can end every device; one row ends one device.
 */
export function sessionMatchesUser(claims: SessionClaims, user: SessionSubject): boolean {
  if (!user) return false;
  return user.status === "ACTIVE" && user.sessionVersion === claims.sessionVersion;
}

export function isSessionActive(expiresAt: Date, now = new Date()): boolean {
  return expiresAt.getTime() > now.getTime();
}